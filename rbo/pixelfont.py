GLYPHS = {c: [(x, y) for y, row in enumerate(rows) for x, v in enumerate(row) if v == "1"]
          for c, rows in _G.items()}


class PixelFont:
    """Stands in for an ImageFont: `size` and `getlength` like Pillow's."""

    def __init__(self, px: int):
        self.size = px
        self.unit = max(1.0, px * 0.78 / 7)      # cap height ~ 0.78 of the size

    def getlength(self, s: str) -> float:
        return len(s) * 6 * self.unit

    def draw(self, d, x: float, y: float, c: str, fill, stroke=None, stroke_w: int = 0) -> None:
        """Draw one character with its baseline at y."""
        u = self.unit
        top = y - 7 * u
        pts = GLYPHS.get(c.upper(), ())
        if stroke and stroke_w:
            for gx, gy in pts:
                d.rectangle([x + gx * u - stroke_w, top + gy * u - stroke_w,
                             x + (gx + 1) * u + stroke_w - 1, top + (gy + 1) * u + stroke_w - 1], fill=stroke)
        for gx, gy in pts:
            d.rectangle([x + gx * u, top + gy * u, x + (gx + 1) * u - 1, top + (gy + 1) * u - 1], fill=fill)
